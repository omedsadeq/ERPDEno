<?php
require_once __DIR__ . '/../../classes/Payment.php';
require_once __DIR__ . '/../../classes/AccountingLedger.php';
(function () use ($t) {
    $db = Database::getInstance(); $pdo = $db->getConnection();
    $doc = fx_user('doctor'); $otherDoc = fx_user('doctor'); $admin = fx_user('admin');
    $pat = fx_patient(); $folder = fx_folder($pat, $doc); $case = fx_case($folder);
    $invoice = fx_invoice($case, $doc, 'sent', 'approved', 100000); fx_treatment($case, 100000, $invoice);
    $service = new Payment(); $ledger = new AccountingLedger();
    $data = ['case_id' => $case, 'amount' => 30000, 'notes' => 'Doctor dialog', 'idempotency_key' => uniqid('dialog-')];
    $t->assertSame(false, $service->saveAndSendDraft($data, $otherDoc)['success'], 'other doctor cannot send');
    $t->assertSame(false, $service->saveAndSendDraft($data, $admin)['success'], 'doctor action excludes admin');
    $sent = $service->saveAndSendDraft($data, $doc);
    $t->assertTrue($sent['success'], 'doctor sends a new request in one submission');
    $row = $service->getById($sent['payment_id']);
    $t->assertSame('pending', $row['status'], 'request is pending approval');
    $t->assertEqualsMoney(30000, $row['amount'], 'entered amount retained');
    $t->assertSame($invoice, (int)$row['allocations'][0]['invoice_id'], 'request allocated to invoice');
    $t->assertEqualsMoney(0, $ledger->getInvoice($invoice)['paid_amount'], 'request does not book money');
    $t->assertSame('approved', $ledger->getInvoice($invoice)['accounting_status'], 'invoice approval state retained');
    $again = $service->saveAndSendDraft($data, $doc);
    $t->assertTrue(!empty($again['duplicate']), 'repeat submission deduplicated');
    $t->assertSame((int)$sent['payment_id'], (int)$again['payment_id'], 'repeat reuses the same receipt');
    $t->assertSame(1, (int)$db->count('payments', 'case_id=?', [$case]), 'only one request created');
    $saved = $service->saveDraft(['case_id' => $case, 'amount' => 40000], $doc);
    $t->assertSame('draft', $service->getById($saved['payment_id'])['status'], 'optional save remains draft');
    $edited = ['case_id' => $case, 'amount' => 45000, 'idempotency_key' => uniqid('dialog-edit-')];
    $res = $service->saveAndSendDraft($edited, $doc, $saved['payment_id']);
    $t->assertTrue($res['success'], 'edited draft sends directly from dialog');
    $t->assertSame((int)$saved['payment_id'], (int)$res['payment_id'], 'editing keeps same receipt');
    $t->assertEqualsMoney(45000, $service->getById($res['payment_id'])['amount'], 'edited amount sent');
    $t->assertSame('pending', $service->getById($res['payment_id'])['status'], 'edited draft enters approval queue');
    $stale = $service->saveAndSendDraft(['case_id' => $case, 'amount' => 45000, 'idempotency_key' => uniqid('stale-')], $doc, $saved['payment_id']);
    $t->assertTrue(!empty($stale['duplicate']), 'stale draft form does not create a new request');
    $t->assertSame(2, (int)$db->count('payments', 'case_id=?', [$case]), 'exactly two legitimate requests');
    $t->assertSame(false, $service->saveAndSendDraft(['case_id' => $case, 'amount' => 30000], $doc)['success'], 'pending requests constrain available balance');
    $db->update('cases', ['status' => 'closed'], 'id=?', [$case]);
    $t->assertSame(false, $service->saveAndSendDraft(['case_id' => $case, 'amount' => 1000], $doc)['success'], 'closed case cannot send');

    $retryCase = fx_case($folder); $retryInvoice = fx_invoice($retryCase, $doc, 'sent', 'approved', 20000);
    $retryData = ['case_id' => $retryCase, 'amount' => 7000, 'idempotency_key' => uniqid('dialog-retry-')];
    $pdo->exec("CREATE TRIGGER test_fail_dialog_send BEFORE UPDATE ON payments FOR EACH ROW BEGIN IF NEW.case_id=$retryCase AND NEW.status='pending' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Simulated send failure'; END IF; END");
    $failed = $service->saveAndSendDraft($retryData, $doc);
    $pdo->exec('DROP TRIGGER test_fail_dialog_send');
    $t->assertSame(false, $failed['success'], 'send error returned to doctor');
    $kept = $db->fetch('SELECT * FROM payments WHERE case_id=?', [$retryCase]);
    $t->assertSame('draft', $kept['status'], 'failed send preserves draft');
    $t->assertEqualsMoney(7000, $kept['amount'], 'entered amount survives failed send');
    $t->assertSame(0, (int)$db->count('payment_allocations', 'payment_id=?', [$kept['id']]), 'failed send reserves no balance');
    $retry = $service->saveAndSendDraft($retryData, $doc);
    $t->assertTrue($retry['success'], 'doctor retries successfully');
    $t->assertSame((int)$kept['id'], (int)$retry['payment_id'], 'retry uses preserved draft');
    $t->assertSame(1, (int)$db->count('payments', 'case_id=?', [$retryCase]), 'retry creates no duplicate');
})();
