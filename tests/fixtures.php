// case_invoices: case_id, invoice_seq, invoice_no, work_date NOT NULL with no
// default (added by database/migrations/2026_08_23_case_invoices.sql, doctor_id
// and accounting_status by 2026_08_25_invoice_accounting_ledger.sql).
// invoice_seq is the next sequence number for that case (UNIQUE (case_id, invoice_seq)).
function fx_invoice($caseId, $doctorId, $status, $accountingStatus, $total) {
    $db = fx_db();
    $seq = (int) $db->fetch(
        'SELECT COALESCE(MAX(invoice_seq), 0) + 1 AS next_seq FROM case_invoices WHERE case_id = ?',
        [$caseId]
    )['next_seq'];
    return (int) $db->insert('case_invoices', [
        'case_id'           => $caseId,
        'doctor_id'         => $doctorId,
        'invoice_seq'       => $seq,
        'invoice_no'        => 'T' . $caseId . '-' . $seq,
        'work_date'         => date('Y-m-d'),
        'total_amount'      => $total,
        'status'            => $status,
        'accounting_status' => $accountingStatus,
    ]);
}
